/**
 * Inlines model-catalog.yaml into a generated TS module so ModelCatalog can
 * load the shipped catalog with no loose YAML beside the bundle. A plain
 * generated `.ts` file works unchanged across tsup and tsx — no loaders needed.
 *
 * Runs via the `build:gen` script before build/typecheck/test/dev. The
 * generated output (src/catalog/modelCatalog.gen.ts) is gitignored.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const yaml = readFileSync(join(root, 'src/catalog/model-catalog.yaml'), 'utf-8');

const out = `// AUTO-GENERATED by scripts/generate-catalog.mjs — do not edit.
export const shippedModelCatalogYaml = ${JSON.stringify(yaml)} as const;
`;
writeFileSync(join(root, 'src/catalog/modelCatalog.gen.ts'), out);
