/**
 * Inlines the local Code Mode MCP client into a generated TS module so
 * install paths can self-serve the script with no loose fixture files.
 * A plain generated `.ts` file works unchanged across tsc and @swc/jest.
 *
 * Runs via `build:gen` before build/typecheck/test. The generated output
 * (src/sandbox/local/sandboxScripts.gen.ts) is gitignored.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const scriptsDir = join(root, 'src/sandbox/local/scripts');
const read = f => readFileSync(join(scriptsDir, f), 'utf-8');

const out = `// AUTO-GENERATED by scripts/generate-local-sandbox-scripts.mjs — do not edit.
export const sandboxScripts = {
  mcpClientLocal: ${JSON.stringify(read('mcp_client_local.py'))},
} as const;
`;
writeFileSync(join(root, 'src/sandbox/local/sandboxScripts.gen.ts'), out);
