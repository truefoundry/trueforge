/**
 * Inlines the sandbox Python helper scripts into a generated TS module so
 * `Sandbox` can self-serve its scripts with no loose files in the package.
 * A plain generated `.ts` file works unchanged across tsup, plain `tsc`
 * (the .d.ts build), and @swc/jest — no loaders or transforms needed.
 *
 * Also inlines the release-owned sandbox image name from
 * scripts/sandbox/sandbox-image.txt (CI updates that file on image pushes).
 *
 * Runs via the `build:gen` script before build/typecheck/test. The generated
 * outputs (src/core/sandbox/*.gen.ts) are gitignored.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const scriptsDir = join(root, 'src/core/sandbox/scripts');
const read = f => readFileSync(join(scriptsDir, f), 'utf-8');

const out = `// AUTO-GENERATED by scripts/generate-sandbox-scripts.mjs — do not edit.
export const sandboxScripts = {
  mcpClient: ${JSON.stringify(read('mcp_client.py'))},
  gitDownloader: ${JSON.stringify(read('git_downloader.py'))},
} as const;
`;
writeFileSync(join(root, 'src/core/sandbox/sandboxScripts.gen.ts'), out);

const imageFile = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'sandbox/sandbox-image.txt'), 'utf-8');
const imageMatch = imageFile.match(/^SANDBOX_IMAGE_NAME=(.+)$/m);
if (!imageMatch) {
  throw new Error('scripts/sandbox/sandbox-image.txt must contain a SANDBOX_IMAGE_NAME=<image> line');
}
const imageOut = `// AUTO-GENERATED by scripts/generate-sandbox-scripts.mjs — do not edit.
// Source of truth: scripts/sandbox/sandbox-image.txt (updated by CI on image pushes).
export const SANDBOX_IMAGE_NAME = ${JSON.stringify(imageMatch[1].trim())};
`;
writeFileSync(join(root, 'src/core/sandbox/sandboxImage.gen.ts'), imageOut);
